import { test, expect } from '@playwright/test'
test.use({ hasTouch: true, isMobile: true })

test('street phone HUD remains usable on mobile and drives the visible flashlight', async ({ page }) => {
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  await page.setViewportSize({ width: 900, height: 650 })
  // Enter the controllable street directly; all HUD and render code stays real.
  await page.route('**/src/game.js', async route => {
    const response = await route.fetch()
    const body = (await response.text())
      .replace("phase: 'party', introElapsed", "phase: 'streetRun', introElapsed")
      .replace('pursuer: { ...spots.entry }', 'pursuer: { x: -100, z: 0 }')
    await route.fulfill({ response, body })
  })
  await page.goto('/')
  await page.locator('#begin').click()
  await expect(page.locator('#phone-toggle')).toBeVisible()
  await expect(page.locator('#touch')).toBeVisible()
  await expect(page.locator('#phone-toggle')).toHaveAttribute('aria-pressed', 'true')
  await page.waitForFunction(() => performance.getEntriesByType('resource').some(entry => entry.name.includes('street-kit.glb') && entry.responseEnd > 0))
  await page.waitForTimeout(600)
  await page.screenshot({ path: 'test-results/street-phone-on.png' })
  await page.locator('#phone-toggle').tap()
  await expect(page.locator('#phone-warning')).toBeVisible()
  await expect(page.locator('#phone-toggle')).toHaveAttribute('aria-pressed', 'false')
  await page.screenshot({ path: 'test-results/street-phone-off.png' })
  await page.keyboard.press('f')
  await expect(page.locator('#phone-toggle')).toHaveAttribute('aria-pressed', 'true')
  await page.setViewportSize({ width: 390, height: 844 })
  const button = await page.locator('#phone-toggle').boundingBox()
  expect(button.height).toBeGreaterThanOrEqual(44)
  expect(button.y + button.height).toBeLessThan(844)
  await page.screenshot({ path: 'test-results/street-mobile.png' })
  await page.keyboard.down('d')
  await expect(page.locator('#game')).toHaveAttribute('data-phase', 'streetSafe', { timeout: 18000 })
  await page.keyboard.up('d')
  await page.setViewportSize({ width: 900, height: 650 })
  await page.screenshot({ path: 'test-results/intersection-safe.png' })
  expect(errors).toEqual([])
})
